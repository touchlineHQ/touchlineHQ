export function getOutcome(result: Pick<LiveResult, 'goals_for' | 'goals_against'>): 'W' | 'D' | 'L' | null {
  if (result.goals_for === null || result.goals_against === null) return null;
  if (result.goals_for > result.goals_against) return 'W';
  if (result.goals_for === result.goals_against) return 'D';
  return 'L';
}

function inWeek(iso: string, weekStart: string): boolean {
  return iso >= weekStart && iso <= addDays(weekStart, 6);
}

/**
 * Strip the club name off the front of a team name — "East Leake Blue U10" reads
 * as "Blue U10" once the club is named in the message header. Falls back to the
 * full name when stripping would leave nothing.
 */
export function stripClubPrefix(teamName: string, clubName: string): string {
  const prefix = clubName.trim();
  if (!prefix) return teamName;
  if (!teamName.toLowerCase().startsWith(`${prefix.toLowerCase()} `)) return teamName;
  return teamName.slice(prefix.length).trim() || teamName;
}

const FRIENDLY_RE = /\bfriendl(?:y|ies)\b/i;

/**
 * Explain a withheld score for a match old enough to have one. Age is not
 * consulted: U11 and below is settled by compliance before this is reached.
 */
export function unscoredReason(row: Pick<LiveResult, 'division'>): UnscoredReason {
  return FRIENDLY_RE.test(row.division) ? 'friendly' : 'withheld';
}

/** Group rows sharing a fixture id — two rows means both sides are this club's. */
function groupById<T extends { id: string }>(rows: T[]): T[][] {
  const groups = new Map<string, T[]>();
  for (const row of rows) {
    const existing = groups.get(row.id);
    if (existing) existing.push(row);
    else groups.set(row.id, [row]);
  }
  return [...groups.values()];
}

function byKickOff(a: { date: string; time: string }, b: { date: string; time: string }): number {
  return a.date.localeCompare(b.date) || a.time.localeCompare(b.time);
}

/**
 * Mondays of every week the club played in, newest first. Participation games
 * count: a club with only U11-and-below teams has no scored results at all, and
 * without them it would be offered no weeks to look at.
 */
export function weeksWithMatches(feed: ClubFeed, now: Date = new Date()): string[] {
  const weeks = new Set<string>();
  const seenIds = new Set<string>();
  for (const result of feed.results) {
    seenIds.add(result.id);
    weeks.add(mondayOf(result.date));
  }
  for (const entry of feed.participation ?? []) {
    if (entry.played === false) continue;
    seenIds.add(entry.id);
    weeks.add(mondayOf(entry.date));
  }
  for (const fixture of feed.fixtures) {
    if (seenIds.has(fixture.id)) continue;
    if (!isRowRestricted(fixture)) continue;
    if (!hasKickedOff(fixture.date, fixture.time, now)) continue;
    weeks.add(mondayOf(fixture.date));
  }
  return [...weeks].sort((a, b) => b.localeCompare(a));
}

/** The week the roundup opens on: the most recent one the club played in. */
export function defaultWeek(feed: ClubFeed): string | null {
  return weeksWithMatches(feed)[0] ?? null;
}

/**
 * Whether a fixture's kick-off is far enough in the past to call it played.
 * Both sides are local wall-clock: a 10am kick-off is 10am where the game is.
 */
function hasKickedOff(date: string, time: string, now: Date): boolean {
  const [year, month, day] = date.split('-').map(Number);
  const [hours, minutes] = (time || '00:00').split(':').map(Number);
  const kickOff = new Date(
    year, month - 1, day,
    Number.isFinite(hours) ? hours : 0,
    Number.isFinite(minutes) ? minutes : 0,
  );
  return now.getTime() - kickOff.getTime() >= KICK_OFF_GRACE_MS;
}

/**
 * Past fixtures with no result recorded, for ages where none ever will be.
 *
 * Some leagues publish no results row whatsoever at U11 and below, so those
 * matches only ever exist as fixtures. Once the kick-off has passed they were
 * played, and belong in the roundup as participation games rather than sitting
 * in the fixture list for ever.
 *
 * Deliberately limited to restricted ages: at open age a fixture with no result
 * is more likely waiting on the league or postponed, and calling it played
 * would assert something we do not know.
 */
function playedWithoutResult(
  fixtures: LiveFixture[],
  weekStart: string,
  seenIds: Set<string>,
  now: Date,
): LiveFixture[] {
  return fixtures.filter(fixture =>
    inWeek(fixture.date, weekStart)
    && !seenIds.has(fixture.id)
    && isRowRestricted(fixture)
    && hasKickedOff(fixture.date, fixture.time, now));
}

function isStale(generated: string): boolean {
  const stamp = Date.parse(generated);
  if (Number.isNaN(stamp)) return false;
  return Date.now() - stamp > STALE_AFTER_HOURS * 60 * 60 * 1000;
}

export function buildRoundup(feed: ClubFeed, weekStart: string, now: Date = new Date()): Roundup {
  const club = feed.club;
  const strip = (name: string) => stripClubPrefix(name, club);
  const matches: RoundupMatch[] = [];
  // Every match id already placed. Fixtures, results and participation entries
  // share one id for the same match (all hashed from date and both team names),
  // so this keeps the three sources from listing it more than once.
  const seenIds = new Set<string>();

  for (const group of groupById(feed.results.filter(r => inWeek(r.date, weekStart)))) {
    const [row] = group;
    seenIds.add(row.id);

    // U11 and below must carry no score, opposition or venue. The feed sends
    // these as participation entries, so this only fires on a stale cached feed
    // or one from a source we do not control. Redact rather than drop: the
    // match still happened.
    if (isRowRestricted(row)) {
      seenIds.add(row.id);
      matches.push(toParticipation({
        id: row.id,
        date: row.date,
        time: row.time,
        team: row.team,
        home_away: row.home_away,
        division: row.division,
        age_group: null,
      }, strip));
      continue;
    }

    if (group.length > 1) {
      // Both sides belong to this club. Use the neutral home/away scores rather
      // than either row's club-side perspective, and award no outcome.
      if (row.home_score === null || row.away_score === null) {
        matches.push(toUnscored(row, strip));
        continue;
      }
      matches.push({
        kind: 'derby',
        id: row.id,
        date: row.date,
        time: row.time,
        homeTeam: strip(row.home_team),
        awayTeam: strip(row.away_team),
        homeScore: row.home_score,
        awayScore: row.away_score,
        division: row.division,
      });
      continue;
    }

    const outcome = getOutcome(row);
    if (outcome === null) {
      matches.push(toUnscored(row, strip));
      continue;
    }
    matches.push({
      kind: 'result',
      id: row.id,
      date: row.date,
      time: row.time,
      team: strip(row.team),
      opponent: row.opponent,
      homeAway: row.home_away,
      goalsFor: row.goals_for as number,
      goalsAgainst: row.goals_against as number,
      outcome,
      division: row.division,
    });
  }

  for (const entry of feed.participation ?? []) {
    if (!inWeek(entry.date, weekStart)) continue;
    // `played: false` marks one still to come; a roundup reports what happened.
    if (entry.played === false) continue;
    if (seenIds.has(entry.id)) continue;
    seenIds.add(entry.id);
    matches.push(toParticipation(entry, strip));
  }

  for (const fixture of playedWithoutResult(feed.fixtures, weekStart, seenIds, now)) {
    seenIds.add(fixture.id);
    matches.push(toParticipation({
      id: fixture.id,
      date: fixture.date,
      time: fixture.time,
      team: fixture.team,
      home_away: fixture.home_away,
      division: fixture.division,
      age_group: null,
    }, strip));
  }

  matches.sort(byKickOff);

  return {
    club,
    weekStart,
    weekEnd: addDays(weekStart, 6),
    matches,
    summary: summarise(matches),
    generated: feed.generated,
    stale: isStale(feed.generated),
  };
}

function toParticipation(
  entry: Pick<ParticipationEntry, 'id' | 'date' | 'time' | 'team' | 'home_away' | 'division'>
    & { age_group?: string | null },
  strip: (name: string) => string,
): RoundupParticipationLine {
  return {
    kind: 'participation',
    id: entry.id,
    date: entry.date,
    time: entry.time,
    team: strip(entry.team),
    homeAway: entry.home_away,
    division: entry.division,
    ageGroup: entry.age_group ?? null,
  };
}

function toUnscored(
  row: LiveResult,
  strip: (name: string) => string,
): RoundupUnscoredLine {
  return {
    kind: 'unscored',
    id: row.id,
    date: row.date,
    time: row.time,
    team: strip(row.team),
    opponent: row.opponent,
    homeAway: row.home_away,
    division: row.division,
    reason: unscoredReason(row),
  };
}

/**
 * Played/W/D/L and goals over the scored, non-derby matches. Derbies are left
 * out on purpose: a club-v-club match is simultaneously a win and a loss for the
 * club, so counting it would make the record say something untrue. Unscored
 * matches have no result to count. Both exclusions keep played === W + D + L.
 */
function summarise(matches: RoundupMatch[]): RoundupSummary {
  const summary: RoundupSummary = {
    played: 0, won: 0, drawn: 0, lost: 0, goalsFor: 0, goalsAgainst: 0,
  };
  for (const match of matches) {
    if (match.kind !== 'result') continue;
    summary.played += 1;
    if (match.outcome === 'W') summary.won += 1;
    else if (match.outcome === 'D') summary.drawn += 1;
    else summary.lost += 1;
    summary.goalsFor += match.goalsFor;
    summary.goalsAgainst += match.goalsAgainst;
  }
  return summary;
}

