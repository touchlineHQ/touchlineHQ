const OUTCOME_EMOJI: Record<'W' | 'D' | 'L', string> = { W: '🟢', D: '🟡', L: '🔴' };
const DERBY_EMOJI = '⚪';
const UNSCORED_EMOJI = '🔵';

/** The span the matches actually cover, which reads better than the full week. */
function matchRange(roundup: Roundup): string {
  const dates = roundup.matches.map(match => match.date).sort();
  if (dates.length === 0) return formatDayRange(roundup.weekStart, roundup.weekEnd);
  return formatDayRange(dates[0], dates[dates.length - 1]);
}

/** The coloured dot that opens a line; a bracketed letter when emoji are off. */
function marker(match: RoundupMatch, emoji: boolean): string {
  if (match.kind === 'result') {
    return emoji ? `${OUTCOME_EMOJI[match.outcome]} ` : `(${match.outcome}) `;
  }
  // A derby and a scoreless match both read unambiguously without emoji — the
  // derby from its neutral scoreline, the others from having no score at all.
  if (match.kind === 'derby') return emoji ? `${DERBY_EMOJI} ` : '';
  return emoji ? `${UNSCORED_EMOJI} ` : '';
}

/** The match itself, without the marker or the kick-off prefix. */
function matchBody(match: RoundupMatch): string {
  if (match.kind === 'result') {
    return `${match.team} ${match.goalsFor}–${match.goalsAgainst} ${match.opponent}`;
  }
  if (match.kind === 'derby') {
    return `${match.homeTeam} ${match.homeScore}–${match.awayScore} ${match.awayTeam}`;
  }
  if (match.kind === 'participation') {
    // Naming the opposition or venue is exactly what the guidance forbids, so
    // the line reports only that this team played, and where they travelled.
    return `${match.team} played ${match.homeAway === 'home' ? 'at home' : 'away'}`;
  }
  const suffix = match.reason === 'friendly' ? ' (friendly)' : '';
  return `${match.team} vs ${match.opponent}${suffix}`;
}

/** "🟢 Sun 10am · Blue U10 4–1 Ruddington Village U10" */
export function matchLine(match: RoundupMatch, emoji: boolean): string {
  return `${marker(match, emoji)}${formatKickOffLabel(match.date, match.time)} · ${matchBody(match)}`;
}

/**
 * One line explaining the blue dots, built only from the reasons actually
 * present so it never claims a cause this week's matches don't have.
 */
function unscoredNote(roundup: Roundup, emoji: boolean): string | null {
  const unscored = unscoredMatches(roundup);
  const participation = participationMatches(roundup);
  if (unscored.length === 0 && participation.length === 0) return null;

  const causes: string[] = [];
  if (participation.length > 0) causes.push('U11 and below');
  if (unscored.some(line => line.reason === 'friendly')) causes.push('friendlies');
  const why = causes.length > 0 ? ` — ${causes.join(', ')}` : '';
  return `${emoji ? `${UNSCORED_EMOJI} ` : ''}No score published${why}`;
}

function summaryLine(summary: RoundupSummary): string {
  const { played, won, drawn, lost, goalsFor, goalsAgainst } = summary;
  return `P${played} · W${won} D${drawn} L${lost} · GF ${goalsFor} GA ${goalsAgainst}`;
}

export function formatWhatsApp(roundup: Roundup, options: FormatOptions = {}): string {
  const { includeLink = true, emoji = true, link = '' } = options;
  const blocks: string[] = [];

  blocks.push(
    `${emoji ? '⚽ ' : ''}${roundup.club} — Weekly Roundup\n${matchRange(roundup)}`,
  );

  if (roundup.matches.length > 0) {
    blocks.push(roundup.matches.map(match => matchLine(match, emoji)).join('\n'));
  } else {
    blocks.push('No results published for this week.');
  }

  if (roundup.summary.played > 0) {
    blocks.push(`${emoji ? '📊 ' : ''}${summaryLine(roundup.summary)}`);
  }

  const note = unscoredNote(roundup, emoji);
  if (note) blocks.push(note);

  if (includeLink && link) blocks.push(`Full results:\n${link}`);

  return blocks.join('\n\n');
}

/** A hashtag from the club name: "East Leake FC" -> "#EastLeakeFC". */
function clubHashtag(club: string): string {
  const words = club.replace(/[^\p{L}\p{N} ]/gu, '').split(/\s+/).filter(Boolean);
  return words.length > 0 ? `#${words.join('')}` : '';
}

export interface SocialMessage {
  text: string;
  length: number;
  /** Lines were dropped to fit SOCIAL_LIMIT. */
  truncated: boolean;
}

/**
 * The social variant has to fit X's 280 characters, so it is composed at
 * decreasing levels of detail and the longest version that fits wins.
 */
export function formatSocial(roundup: Roundup, options: FormatOptions = {}): SocialMessage {
  const { includeLink = true, emoji = true, link = '' } = options;
  const { summary } = roundup;

  const header = `${emoji ? '⚽ ' : ''}${roundup.club} weekend roundup`;
  const record = summary.played > 0 ? `W${summary.won} D${summary.drawn} L${summary.lost}` : '';
  const tags = [clubHashtag(roundup.club), '#GrassrootsFootball'].filter(Boolean).join(' ');
  const tail = includeLink && link ? link : '';

  const compose = (shown: number, withTags: boolean): string => {
    const blocks: string[] = [record ? `${header}\n${record}` : header];

    if (roundup.matches.length === 0) {
      blocks.push('No results published this week.');
    } else {
      const lines = roundup.matches.slice(0, shown).map(match => matchLine(match, emoji));
      const hidden = roundup.matches.length - shown;
      if (hidden > 0) lines.push(`+${hidden} more`);
      blocks.push(lines.join('\n'));
    }

    if (withTags && tags) blocks.push(tags);
    if (tail) blocks.push(tail);
    return blocks.join('\n\n');
  };

  const total = roundup.matches.length;
  for (const withTags of [true, false]) {
    for (let shown = total; shown >= 1; shown--) {
      const text = compose(shown, withTags);
      const length = xWeightedLength(text);
      if (length <= SOCIAL_LIMIT) {
        return { text, length, truncated: shown < total };
      }
    }
  }

  // Nothing fits — hand back the shortest form and let the UI show it over budget.
  const text = compose(1, false);
  return { text, length: xWeightedLength(text), truncated: total > 1 };
}

export function formatEmailSubject(roundup: Roundup): string {
  return `${roundup.club} results — week ending ${formatDayShort(roundup.weekEnd)}`;
}

export function formatEmailBody(roundup: Roundup, options: FormatOptions = {}): string {
  const { includeLink = true, emoji = false, link = '' } = options;
  const blocks: string[] = [];

  blocks.push(`Results, ${matchRange(roundup)}`);

  if (roundup.matches.length > 0) {
    blocks.push(roundup.matches.map(match => `  ${matchLine(match, emoji)}`).join('\n'));
  } else {
    blocks.push('  No results published for this week.');
  }

  if (roundup.summary.played > 0) {
    const { played, won, drawn, lost, goalsFor, goalsAgainst } = roundup.summary;
    blocks.push(
      `Played ${played}  Won ${won}  Drawn ${drawn}  Lost ${lost}\n` +
      `Goals for ${goalsFor}, against ${goalsAgainst}`,
    );
  }

  const note = unscoredNote(roundup, emoji);
  if (note) blocks.push(note);

  if (includeLink && link) blocks.push(`Full results: ${link}`);
  blocks.push('Results from FA Full-Time via touchlineHQ.');

  return blocks.join('\n\n');
}
